import JSZip from "jszip";
import type { BoardDesign } from "../domain/types";
import { buildHarvestManifest } from "./harvester";

export function buildEasyEdaProjectJson(design: BoardDesign) {
  return {
    format: "easyeda-standard-project",
    generator: "blockless-pcb-studio",
    review_note: "Review design rules, footprints, and manufacturing settings in JLC EDA before fabrication.",
    board: {
      title: design.title,
      size_mm: design.boardSizeMm,
      layers: 2,
      outline: [
        [0, 0],
        [design.boardSizeMm.w, 0],
        [design.boardSizeMm.w, design.boardSizeMm.h],
        [0, design.boardSizeMm.h],
      ],
    },
    modules: design.selectedModules.map(({ module }) => ({
      id: module.id,
      name: module.name,
      size_mm: module.sizeMm,
      connector: module.connector,
      source: module.source,
      purchase_url: module.purchaseUrl,
      model3d: module.model3d,
      review_status: module.reviewStatus,
      placement: design.placements.find((placement) => placement.moduleId === module.id),
      pins: module.pins,
    })),
    nets: design.nets,
    tracks: design.tracks,
    keepouts: design.keepouts,
    checks: design.report,
  };
}

export function buildBomCsv(design: BoardDesign): string {
  const header = ["Item", "Module ID", "Name", "Qty", "Connector", "Source", "Unit Price USD", "Purchase URL"];
  const rows = design.bom.map((line) => [
    line.item,
    line.moduleId,
    line.name,
    line.qty,
    line.connector,
    line.source,
    line.unitPriceUsd.toFixed(2),
    line.purchaseUrl,
  ]);

  return [header, ...rows]
    .map((row) => row.map((cell) => `"${String(cell).replace(/"/g, '""')}"`).join(","))
    .join("\n");
}

export function buildReportJson(design: BoardDesign): string {
  return JSON.stringify(
    {
      title: design.title,
      prompt: design.prompt,
      summary: design.report.summary,
      erc: design.report.erc,
      drc: design.report.drc,
      dfm: design.report.dfm,
      manual_review_required: design.selectedModules
        .filter((item) => item.module.reviewStatus !== "verified")
        .map((item) => ({
          module: item.module.name,
          status: item.module.reviewStatus,
          notes: item.module.reviewNotes,
        })),
      harvested_assets: buildHarvestManifest(design.selectedModules),
    },
    null,
    2,
  );
}

export async function downloadExportZip(design: BoardDesign) {
  const zip = new JSZip();
  zip.file("board.easyeda.json", JSON.stringify(buildEasyEdaProjectJson(design), null, 2));
  zip.file("module-assets.json", JSON.stringify(buildHarvestManifest(design.selectedModules), null, 2));
  zip.file("bom.csv", buildBomCsv(design));
  zip.file("report.json", buildReportJson(design));
  zip.file(
    "README.md",
    [
      `# ${design.title}`,
      "",
      "This package is generated by Blockless PCB Studio.",
      "",
      "Included outputs: module selection, interface matching, board placement, routing data, BOM, checks, and JLC EDA oriented project export.",
      "",
      "Review design rules, footprints, and manufacturing settings in JLC EDA before fabrication.",
      "",
    ].join("\n"),
  );

  const blob = await zip.generateAsync({ type: "blob" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = `${design.id}-jlc-package.zip`;
  document.body.appendChild(link);
  link.click();
  link.remove();
  URL.revokeObjectURL(url);
}
